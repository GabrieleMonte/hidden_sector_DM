"""Phase-3 rerun campaign: generate the driver variants the campaign needs.

The committed `make_relic_grid_vP*.py` drivers carry the PASS-A config.  Pass B
and Stage 5 differ from them only in CAMPAIGN-tagged constants, and the campaign
runs all of its slices concurrently, so each config needs its own file rather
than a hand edit between submissions (docs/phase3_rerun_campaign.md).

    python GCE/scripts/phase3_make_variants.py            # write the variants
    python GCE/scripts/phase3_make_variants.py --check     # verify, write nothing

Generated (all with RUN_SECLUDED=False inherited from the pass-A drivers):

  *_passB.py    EPS_JOINT -> (1e-10,), ONLY_RV_COLUMNS -> cols 57-66 (rv >= 0.636).
                One per xi_ini slice.  460 nodes each.
  *_stage5.py   xi_ini = 1 only: the LEGACY-path backfill of the 662 eps=1e-9
                nodes at rv < 0.465 that the 34->67 bisection never filled.
                ONLY_RV_COLUMNS -> cols 0-49, PHASE3_KW -> {} and SOLVE_TIMEOUT
                -> 2700 so the backfilled nodes match their trusted neighbours.
                ALPHAX_LIMS[1e-9] stays (2e-5, 1.0): phase3_invalidate.py wrote
                that axis into the file, and load_state compares it exactly.

Every substitution is anchored and asserted, so a drift in the source drivers
fails here instead of silently producing a wrong-config run.
"""

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

PASS_A_DRIVERS = ["make_relic_grid_vP",
                  "make_relic_grid_vP_xi_ini_0.5",
                  "make_relic_grid_vP_xi_ini_2.5"]
STAGE5_SOURCE = "make_relic_grid_vP"

COMMENT_COL = 41                 # where the drivers align their trailing comments

# Each campaign constant owns an assignment (sometimes several lines, for a dict)
# followed by indented comment-only continuation lines.  An edit replaces that
# whole block, so a generated file never carries a stale PASS-A comment next to a
# PASS-B value.
ANCHORS = {
    "EPS_JOINT":       r"^EPS_JOINT    = \(1e-9,\).*\n",
    "ONLY_RV_COLUMNS": r"^ONLY_RV_COLUMNS = tuple\(range\(50, 67\)\).*\n",
    "SOLVE_TIMEOUT":   r"^SOLVE_TIMEOUT = 7200.*\n",
    "PHASE3_KW":       r"^PHASE3_KW = dict\((?:.*\n)*?"
                       r".*phase3_kw=dict\(rtol_value=1e-6\)\).*\n",
}
CONTINUATION = r"(?:^[ ]+#.*\n)*"


def _block(code, comments):
    """One aligned `code  # comment` block, continuation lines padded to match."""
    pad = " " * COMMENT_COL
    head = f"{code:<{COMMENT_COL}}# {comments[0]}\n"
    return head + "".join(f"{pad}# {c}\n" for c in comments[1:])


PASS_B_EDITS = [
    ("EPS_JOINT", _block("EPS_JOINT    = (1e-10,)", [
        "CAMPAIGN PASS B.  Restore (1e-9, 1e-10)",
        "after the campaign.",
    ]), "EPS_JOINT -> (1e-10,)"),
    ("ONLY_RV_COLUMNS", _block("ONLY_RV_COLUMNS = tuple(range(57, 67))", [
        "CAMPAIGN PASS B: rv >= 0.636, 460 nodes.",
        "Restore None after the campaign.",
    ]), "ONLY_RV_COLUMNS -> cols 57-66"),
]

STAGE5_EDITS = [
    ("ONLY_RV_COLUMNS", _block("ONLY_RV_COLUMNS = tuple(range(0, 50))", [
        "STAGE 5: rv < 0.465 -- the 662 odd-column",
        "nodes the 34->67 bisection never filled.",
        "Restore None when the backfill is done.",
    ]), "ONLY_RV_COLUMNS -> cols 0-49"),
    ("SOLVE_TIMEOUT", _block("SOLVE_TIMEOUT = 2700", [
        "s; STAGE 5 restores the legacy value -- the",
        "backfill must match its trusted neighbours.",
    ]), "SOLVE_TIMEOUT -> 2700 (legacy value)"),
    ("PHASE3_KW", _block("PHASE3_KW = {}", [
        "STAGE 5: legacy path, Phase 3 OFF, so the",
        "backfilled rv < 0.465 nodes match the",
        "trusted neighbours already in the file.",
    ]), "PHASE3_KW -> {}"),
]

BANNER = ("# ---------------------------------------------------------------------\n"
          "# GENERATED by phase3_make_variants.py from {src}.py -- do not hand edit.\n"
          "# {role}\n"
          "# Regenerate with: python GCE/scripts/phase3_make_variants.py\n"
          "# ---------------------------------------------------------------------\n")


def _apply(text, edits, src):
    """Apply each anchored edit exactly once, or raise with the failing anchor."""
    for name, repl, desc in edits:
        pattern = ANCHORS[name] + CONTINUATION
        new, n = re.subn(pattern, repl, text, count=1, flags=re.M)
        if n != 1:
            raise SystemExit(f"{src}: anchor for '{desc}' matched {n} times, expected 1 "
                             f"-- the source driver changed; update phase3_make_variants.py")
        text = new
    return text


def build(stem, suffix, edits, role):
    """Return (path, contents) for one generated variant."""
    src = HERE / f"{stem}.py"
    text = _apply(src.read_text(), edits, src.name)
    lines = text.split("\n")

    # Place the banner after the module docstring so `python -c "import ..."` help
    # and the existing header comments stay first.
    end = 0
    if lines and lines[0].lstrip().startswith(('"""', "'''")):
        quote = lines[0].lstrip()[:3]
        end = 1 if lines[0].strip().endswith(quote) and len(lines[0].strip()) > 3 else None
        if end is None:
            for k in range(1, len(lines)):
                if quote in lines[k]:
                    end = k + 1
                    break
    banner = BANNER.format(src=stem, role=role)
    out = "\n".join(lines[:end]) + "\n" + banner + "\n".join(lines[end:])
    return HERE / f"{stem}{suffix}.py", out


def main():
    ap = argparse.ArgumentParser(description="generate the Phase-3 campaign driver variants")
    ap.add_argument("--check", action="store_true",
                    help="verify the generated files are current; write nothing")
    args = ap.parse_args()

    targets = [build(stem, "_passB", PASS_B_EDITS,
                     "PASS B: eps = 1e-10, rv >= 0.636 (cols 57-66), 460 nodes.")
               for stem in PASS_A_DRIVERS]
    targets.append(build(STAGE5_SOURCE, "_stage5", STAGE5_EDITS,
                         "STAGE 5: legacy-path backfill, eps = 1e-9, rv < 0.465 "
                         "(cols 0-49), 662 nodes."))

    stale = 0
    for path, text in targets:
        current = path.read_text() if path.exists() else None
        if current == text:
            print(f"{path.name}: up to date")
            continue
        stale += 1
        if args.check:
            print(f"{path.name}: STALE" if current else f"{path.name}: MISSING")
            continue
        path.write_text(text)
        print(f"{path.name}: written ({len(text.splitlines())} lines)")

    if args.check and stale:
        sys.exit(f"\n{stale} variant(s) out of date -- run without --check")


if __name__ == "__main__":
    main()
